package juicefs

import "io/fs"

func (c *Client) FS() fs.FS {
	return (*clientFS)(c)
}

type clientFS Client

func (cfs *clientFS) Open(name string) (fs.File, error) {
	if !fs.ValidPath(name) {
		return nil, &fs.PathError{Op: "open", Path: name, Err: fs.ErrInvalid}
	}
	f, err := (*Client)(cfs).Open(name)
	if err != nil {
		return nil, err
	}
	return f, nil
}

func (cfs *clientFS) Stat(name string) (fs.FileInfo, error) {
	if !fs.ValidPath(name) {
		return nil, &fs.PathError{Op: "stat", Path: name, Err: fs.ErrInvalid}
	}
	return (*Client)(cfs).Stat(name)
}

func (cfs *clientFS) Lstat(name string) (fs.FileInfo, error) {
	if !fs.ValidPath(name) {
		return nil, &fs.PathError{Op: "lstat", Path: name, Err: fs.ErrInvalid}
	}
	return (*Client)(cfs).Lstat(name)
}

func (cfs *clientFS) ReadDir(name string) ([]fs.DirEntry, error) {
	if !fs.ValidPath(name) {
		return nil, &fs.PathError{Op: "readdir", Path: name, Err: fs.ErrInvalid}
	}
	return (*Client)(cfs).ReadDir(name)
}

func (cfs *clientFS) ReadFile(name string) ([]byte, error) {
	if !fs.ValidPath(name) {
		return nil, &fs.PathError{Op: "readfile", Path: name, Err: fs.ErrInvalid}
	}
	return (*Client)(cfs).ReadFile(name)
}

func (cfs *clientFS) ReadLink(name string) (string, error) {
	if !fs.ValidPath(name) {
		return "", &fs.PathError{Op: "readlink", Path: name, Err: fs.ErrInvalid}
	}
	return (*Client)(cfs).Readlink(name)
}
